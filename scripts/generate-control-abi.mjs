import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(
  fs.readFileSync(path.join(root, "docs/control-abi-v1.json"), "utf8"),
);

const enumFs = (name, values) => `[<RequireQualifiedAccess>]
type ${name} =
${Object.entries(values)
  .map(([key, value]) => `    | ${key} = ${value}`)
  .join("\n")}
`;

const sectionNames = {
  OwnState: "OwnStateTag",
  ResolvedOrientation: "ResolvedOrientationTag",
  ActionAndRecovery: "ActionAndRecoveryTag",
  ObservationsAndStimuli: "ObservationsAndStimuliTag",
  Events: "EventsTag",
  MessagesAndReports: "MessagesAndReportsTag",
  CapabilityDescriptors: "CapabilityDescriptorsTag",
  ServiceResults: "ServiceResultsTag",
  RequestStatus: "RequestStatusTag",
  OutputRequests: "OutputRequestsTag",
};

const literal = (name, value, suffix = "") =>
  `    [<Literal>]\n    let ${name} = ${value}${suffix}`;

const fsharp = `// <auto-generated>
// Generated by scripts/generate-control-abi.mjs from docs/control-abi-v1.json.
// </auto-generated>
namespace SIR.ControlAbi

[<RequireQualifiedAccess>]
module V1Constants =
${[
  literal("Major", spec.major, "uy"),
  literal("Minor", spec.minor, "uy"),
  literal("HeaderBytes", spec.layout.headerBytes),
  literal("SectionHeaderBytes", spec.layout.sectionHeaderBytes),
  literal("InputMaximumBytes", spec.limits.inputBytes),
  literal("OutputMaximumBytes", spec.limits.outputBytes),
  literal("MaximumSections", spec.limits.sections),
  literal("MaximumElementsPerSection", spec.limits.elementsPerSection),
  literal("MaximumStringBytes", spec.limits.stringUtf8Bytes),
  literal("MaximumOpaquePayloadBytes", spec.limits.opaquePayloadBytes),
  literal("RequiredSectionFlag", "0x0001", "us"),
  ...Object.entries(spec.sections).map(([name, value]) =>
    literal(sectionNames[name], `0x${value.toString(16).padStart(4, "0")}`, "us"),
  ),
].join("\n")}

${enumFs("RequestKind", spec.requestKinds)}
${enumFs("DirectionCode", spec.directionCodes)}
${enumFs("TargetKind", spec.targetKinds)}
${enumFs("MovementPosture", spec.movementPostures)}
${enumFs("EmissionPolicy", spec.emissionPolicies)}
${enumFs("FormationOperation", spec.formationOperations)}
${enumFs("EngagementOperation", spec.engagementOperations)}
${enumFs("ServiceKind", spec.serviceKinds)}
${enumFs("EventKind", spec.eventKinds)}
${enumFs("ModuleStatus", spec.moduleStatuses)}
${enumFs("InvocationFailure", spec.invocationFailures)}
${enumFs("RequestFailure", spec.requestFailures)}
${enumFs("ActionFailure", spec.actionFailures)}`;

const javascript = `// Generated by scripts/generate-control-abi.mjs. Do not edit.
export const CONTROL_ABI_V1 = Object.freeze(${JSON.stringify(spec, null, 2)});
`;

fs.mkdirSync(path.join(root, "generated"), { recursive: true });
fs.writeFileSync(
  path.join(root, "src/SIR.Domain/ControlAbiV1.Generated.fs"),
  fsharp,
);
fs.writeFileSync(
  path.join(root, "generated/control-abi-v1.mjs"),
  javascript,
);
